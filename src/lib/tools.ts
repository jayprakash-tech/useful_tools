/* ---------------- registry helpers ---------------- */

export const getTool = (slug: string) => TOOLS.find((x) => x.slug === slug);

export const toolsByCategory = (cat: string) => TOOLS.filter((x) => x.cat === cat);

export const popularTools = () => TOOLS.filter((x) => x.popular);

export function searchTools(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return TOOLS;
  return TOOLS.filter(
    (x) =>
      x.name.toLowerCase().includes(q) ||
      x.short.toLowerCase().includes(q) ||
      x.formats.some((f) => f.toLowerCase().includes(q)) ||
      x.cat.replace("-", " ").includes(q),
  );
}

export const RELATED = (slug: string): Tool[] => {
  const tool = getTool(slug);
  if (!tool) return [];
  return tool.related.map(getTool).filter((x): x is Tool => Boolean(x));
};
